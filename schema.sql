-- ────────────────────────────────────────────────────────
-- 3. PLATFORM CONNECTIONS TABLE (per-company, per-platform credentials/tokens)
-- ────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.platform_connections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    platform text NOT NULL CHECK (platform IN ('instagram', 'facebook', 'linkedin', 'google_business')),
    auth_type text NOT NULL DEFAULT 'password' CHECK (auth_type IN ('password', 'oauth')),
    credentials jsonb DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'connected',
    connected_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE (company_id, platform)
);

ALTER TABLE public.platform_connections ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow all access to anon" ON public.platform_connections;
CREATE POLICY "Allow all access to anon" ON public.platform_connections FOR ALL TO anon USING (true) WITH CHECK (true);

-- Carry forward any pre-existing single-tenant Instagram credentials (older installs stored
-- them on system_settings) into platform_connections for the seeded company, before that
-- legacy column is dropped below. No-op on fresh installs where the columns never existed.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='system_settings' AND column_name='instagram_username') THEN
        INSERT INTO public.platform_connections (company_id, platform, auth_type, credentials, status)
        SELECT
            (SELECT id FROM public.companies WHERE slug = 'new-gen-studios'),
            'instagram',
            'password',
            jsonb_build_object('username', s.instagram_username, 'password', s.instagram_password),
            'connected'
        FROM public.system_settings s
        WHERE s.id = 'default' AND s.instagram_username IS NOT NULL
        ON CONFLICT (company_id, platform) DO NOTHING;
    END IF;
END $$;

ALTER TABLE public.system_settings DROP COLUMN IF EXISTS instagram_username;
ALTER TABLE public.system_settings DROP COLUMN IF EXISTS instagram_password;


-- ────────────────────────────────────────────────────────
-- 4. POSTS HISTORY TABLE (tracks historical posts per company/platform to prevent repetition)
-- ────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.posts_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid REFERENCES public.companies(id) ON DELETE CASCADE,
    platform text NOT NULL DEFAULT 'instagram',
    date text,
    post_type text,
    idea_summary text,
    reel_or_static text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.posts_history ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow all access to anon" ON public.posts_history;
CREATE POLICY "Allow all access to anon" ON public.posts_history FOR ALL TO anon USING (true) WITH CHECK (true);

ALTER TABLE public.posts_history ADD COLUMN IF NOT EXISTS company_id uuid REFERENCES public.companies(id) ON DELETE CASCADE;
ALTER TABLE public.posts_history ADD COLUMN IF NOT EXISTS platform text NOT NULL DEFAULT 'instagram';

UPDATE public.posts_history
SET company_id = (SELECT id FROM public.companies WHERE slug = 'new-gen-studios')
WHERE company_id IS NULL;


