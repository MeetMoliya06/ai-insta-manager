-- ────────────────────────────────────────────────────────
-- 1. SYSTEM SETTINGS TABLE (operator-level config: Gemini key + dashboard password)
-- ────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.system_settings (
    id text NOT NULL PRIMARY KEY,
    gemini_api_key text,
    dashboard_password_hash text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.system_settings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow all access to anon" ON public.system_settings;
CREATE POLICY "Allow all access to anon" ON public.system_settings FOR ALL TO anon USING (true) WITH CHECK (true);

ALTER TABLE public.system_settings ADD COLUMN IF NOT EXISTS dashboard_password_hash text;


-- ────────────────────────────────────────────────────────
-- 2. COMPANIES TABLE (one row per client/brand managed in the dashboard)
-- ────────────────────────────────────────────────────────
